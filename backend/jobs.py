import threading
import uuid
from collections.abc import Callable
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from backend.audio import SAMPLE_RATE, ExportCancelled, audio_frame_count, mix_audio, render_metronome, write_silence
from backend.models import ExportRequest, Job
from backend.storage import ID_PATTERN, MediaLibrary


class ExportManager:
    def __init__(self, library: MediaLibrary):
        self.library = library
        self.lock = threading.Lock()
        self.jobs: dict[str, Job] = {}
        self.cancellations: dict[str, threading.Event] = {}
        self.executor = ThreadPoolExecutor(max_workers=2, thread_name_prefix="stridemix-export")

    def create(self, request: ExportRequest) -> Job:
        snapshot = request.model_copy(deep=True)
        release = self.library.acquire_tracks([reference.id for reference in snapshot.tracks])
        try:
            return self._create(snapshot, release)
        except Exception:
            release()
            raise

    def _create(self, snapshot: ExportRequest, release: Callable[[], None]) -> Job:
        tracks = {}
        for reference in snapshot.tracks:
            if reference.id not in tracks:
                tracks[reference.id] = self.library.analyze(reference.id)
        paths = [self.library.track_path(reference.id) for reference in snapshot.tracks]
        gap_frames = round(snapshot.gap_seconds * SAMPLE_RATE)
        segments = []
        frame_count = 0
        for index, (reference, path) in enumerate(zip(snapshot.tracks, paths)):
            if index:
                frame_count += gap_frames
            end = frame_count + audio_frame_count(path)
            anchor = tracks[reference.id].alignment.anchor_seconds or 0
            segments.append((frame_count, end, anchor + reference.phase_offset_ms / 1000))
            frame_count = end
        job_id = uuid.uuid4().hex
        job = Job(id=job_id, status="queued")
        with self.lock:
            self.jobs[job_id] = job
            self.cancellations[job_id] = threading.Event()
        self.executor.submit(self._run, job_id, snapshot, paths, frame_count, segments, gap_frames, release)
        return self.get(job_id)

    def get(self, job_id: str) -> Job:
        if not ID_PATTERN.fullmatch(job_id):
            raise KeyError(job_id)
        with self.lock:
            return self.jobs[job_id].model_copy()

    def update(self, job_id: str, **changes) -> None:
        with self.lock:
            current = self.jobs[job_id]
            self.jobs[job_id] = current.model_copy(update=changes)

    def cancel(self, job_id: str) -> Job:
        job = self.get(job_id)
        if job.status in ("queued", "processing"):
            self.cancellations[job_id].set()
        return self.get(job_id)

    def output_path(self, job_id: str) -> Path:
        job = self.get(job_id)
        if job.status != "completed":
            raise ValueError("导出尚未完成")
        files = list((self.library.exports_dir / job_id).glob("stridemix.*"))
        if len(files) != 1:
            raise KeyError(job_id)
        return files[0]

    def _run(
        self, job_id: str, request: ExportRequest, paths: list[Path], frame_count: int,
        segments: list[tuple[int, int, float]], gap_frames: int, release: Callable[[], None],
    ) -> None:
        directory = self.library.exports_dir / job_id
        cancelled = self.cancellations[job_id]
        destination = directory / f"stridemix.{request.format}"
        metronome = directory / "metronome.wav"
        concat_file = directory / "inputs.txt"
        silence_file = directory / "gap.wav"
        directory_created = False
        try:
            directory.mkdir()
            directory_created = True
            if cancelled.is_set():
                raise ExportCancelled()
            self.update(job_id, status="processing", progress=1)
            # Every path below is generated by MediaLibrary, never a user filename.
            lines = []
            if gap_frames and len(paths) > 1:
                write_silence(silence_file, gap_frames, cancelled)
            for index, path in enumerate(paths):
                if index and gap_frames:
                    gap_path = silence_file.as_posix().replace("'", "'\\''")
                    lines.append(f"file '{gap_path}'")
                escaped_path = path.as_posix().replace("'", "'\\''")
                lines.append(f"file '{escaped_path}'")
            concat_file.write_text("\n".join(lines) + "\n", encoding="utf-8")
            render_metronome(
                metronome, frame_count, request.cadence, request.tone, cancelled,
                lambda fraction: self.update(job_id, progress=round(1 + fraction * 19, 1)),
                segments=segments,
            )
            mix_audio(
                concat_file, metronome, destination, frame_count,
                request.bgm_volume, request.beat_volume, cancelled,
                lambda fraction: self.update(job_id, progress=round(20 + fraction * 79, 1)),
            )
            if cancelled.is_set():
                raise ExportCancelled()
            self.update(
                job_id, status="completed", progress=100,
                download_url=f"/api/exports/{job_id}/download",
            )
        except ExportCancelled:
            if directory_created:
                destination.unlink(missing_ok=True)
            self.update(job_id, status="cancelled", error=None)
        except Exception as exc:
            if directory_created:
                destination.unlink(missing_ok=True)
            self.update(job_id, status="failed", error=str(exc)[:1500])
        finally:
            try:
                if directory_created:
                    metronome.unlink(missing_ok=True)
                    concat_file.unlink(missing_ok=True)
                    silence_file.unlink(missing_ok=True)
            finally:
                release()

    def shutdown(self) -> None:
        with self.lock:
            for job_id, job in self.jobs.items():
                if job.status in ("queued", "processing"):
                    self.cancellations[job_id].set()
        self.executor.shutdown(wait=True, cancel_futures=False)
